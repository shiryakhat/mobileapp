/**
 * Builds the coin-flip easter egg's page: one self-contained HTML document, so
 * the WebView that shows it (src/coinflip/CoinStage.tsx) never touches the
 * network. It is the website's own coin: site/assets/coin.js and its three.js
 * bundle are inlined as they are, next to the artwork (as data: URIs).
 *
 *   node scripts/build-coinflip.js     (or: npm run coinflip:build)
 *
 * Run it after changing site/assets/coin.js, the three.js bundle, the template
 * or the artwork in assets/coinflip/. src/__tests__/coinflip.test.tsx fails
 * while the generated module is out of date.
 *
 * assets/coinflip/face-*.webp are site/assets/coin-face-*.png at 1024 px:
 *   cwebp -resize 1024 1024 -q 80 -alpha_q 90 site/assets/coin-face-heads.png -o assets/coinflip/face-heads.webp
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const OUT = path.join(root, 'src/coinflip/coinPage.generated.ts');
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');
const dataUri = (file) =>
  `data:image/webp;base64,${fs.readFileSync(path.join(root, file)).toString('base64')}`;

/** Replace exactly one occurrence; anything else means the sources have moved on. */
function swap(text, from, to, what) {
  const parts = text.split(from);
  if (parts.length !== 2) {
    throw new Error(`build-coinflip: expected one "${what}", found ${parts.length - 1}`);
  }
  return parts.join(to);
}

/** The three.js ES module as an expression: its exports become one object. */
function threeNamespace() {
  const source = read('site/assets/vendor/three.min.js').trim();
  const match = source.match(/export\s*\{([^{}]*)\}\s*;?$/);
  if (!match) throw new Error('build-coinflip: three.min.js does not end in an export list');
  const members = match[1]
    .split(',')
    .map((entry) => entry.trim())
    .filter(Boolean)
    .map((entry) => {
      const [local, name = local] = entry.split(/\s+as\s+/);
      return `${name}:${local}`;
    });
  const body = source.slice(0, match.index);
  return `var THREE = (function () {\n${body}\nreturn {${members.join(',')}};\n})();`;
}

/** site/assets/coin.js as a plain function: no module syntax, artwork inlined. */
function coinSource() {
  let source = read('site/assets/coin.js');
  source = swap(source, "import * as THREE from './vendor/three.min.js';\n", '', 'three import');
  source = swap(source, 'export async function mount(', 'async function mount(', 'mount export');
  source = swap(
    source,
    "  const base = opts.assets || new URL('.', import.meta.url).href;\n",
    '',
    'asset base',
  );
  source = swap(
    source,
    "loadImage(base + 'coin-face-heads.png')",
    `loadImage(${JSON.stringify(dataUri('assets/coinflip/face-heads.webp'))})`,
    'heads artwork',
  );
  source = swap(
    source,
    "loadImage(base + 'coin-face-tails.png')",
    `loadImage(${JSON.stringify(dataUri('assets/coinflip/face-tails.webp'))})`,
    'tails artwork',
  );
  return source;
}

function build() {
  let page = read('assets/coinflip/page.template.html');
  page = swap(page, '__POSTER_HEADS__', dataUri('site/assets/coin-heads.webp'), 'heads poster');
  page = swap(page, '__POSTER_TAILS__', dataUri('site/assets/coin-tails.webp'), 'tails poster');
  page = swap(page, '/*__THREE__*/', threeNamespace(), 'three placeholder');
  page = swap(page, '/*__COIN__*/', coinSource(), 'coin placeholder');
  // Inline scripts end at the first closing tag, wherever it is.
  const inline = page.slice(page.indexOf('<script>') + 8, page.lastIndexOf('</script>'));
  if (/<\/script/i.test(inline)) throw new Error('build-coinflip: "</script" inside the script');
  return page;
}

function moduleSource() {
  return [
    '// Generated by scripts/build-coinflip.js (npm run coinflip:build). Do not edit.',
    `export const COIN_PAGE: string = ${JSON.stringify(build())};`,
    '',
  ].join('\n');
}

module.exports = { build, moduleSource, OUT };

if (require.main === module) {
  fs.writeFileSync(OUT, moduleSource());
  console.log(`${path.relative(root, OUT)}: ${(fs.statSync(OUT).size / 1024).toFixed(0)} kB`);
}
